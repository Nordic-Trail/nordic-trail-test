'use strict';
// Run: node qa/shared-map-20261123/smoke.cjs
// No external dependencies, no network and no Supabase mutations.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const fromRoot=p=>fs.readFileSync(path.resolve(__dirname,'../..',p),'utf8');
const existing=fromRoot('staging-app/index.html');
const host=fromRoot('staging-shared-map-20261123/index.html');
const planner=fromRoot('staging-shared-map-20261123/shared-planner.js');
const m=planner.match(/root\.innerHTML=("(?:\\.|[^"\\])*");/);
assert.ok(m,'shadow UI markup must exist');
const shadow=JSON.parse(m[1]);
const ids=src=>[...src.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
const dup=src=>ids(src).filter((id,i,all)=>all.indexOf(id)!==i);
assert.deepEqual(dup(host),[]);
assert.deepEqual(dup(shadow),[]);
for(const id of ids(existing))assert.ok(ids(host).includes(id),'Original UI missing: '+id);
const collisions=ids(shadow).filter(id=>ids(host).includes(id));
assert.deepEqual(collisions.sort(),['point-kind','points']);
assert.ok(planner.includes('const el=id=>root.getElementById(id);'),'Planner IDs must resolve only in shadow');
assert.ok(host.includes("window.__ntSharedMap=map;"));
assert.ok(planner.includes("map=window.__ntSharedMap;"));
assert.equal((host.match(/L\.map\('map'/g)||[]).length,1,'Exactly one Leaflet map');
assert.ok(!planner.includes('L.map('));
assert.ok(!planner.includes('L.tileLayer('),'No extra map tiles');
assert.ok(host.includes('if(window.__ntPlannerActive)return;'),'Original point form gated while routing');
assert.ok(planner.includes('if(!window.__ntPlannerActive)return;'),'Planner map clicks gated when closed');
assert.ok(planner.includes('host.attachShadow({mode:\'open\'})'));
assert.ok(host.includes("fetch('../staging-app/data/tumba-lida.json'"));
assert.ok(host.includes("https://valhalla1.openstreetmap.de;"));
assert.ok(planner.includes('function safeRoutedGpx')&&!planner.includes('I.gpx(trip,routes)'));
assert.ok(planner.includes('function restoreManualGapDrafts'));
assert.ok(planner.includes("ARCHIVE_KEY='nt-shared-map-trips-20261123-v1'"));
assert.ok(!planner.includes('nt-named-preview-working-20261123:'));
assert.ok(planner.includes('nt-shared-map-working-20261123:'));
assert.ok(!planner.includes('localStorage.setItem(PREVIOUS_INTEGRATION_KEY'));
assert.ok(host.includes("admin_pending_map_points")&&host.includes(".from('map_points')"));
assert.ok(shadow.includes('id="nt-walker"')&&shadow.includes('id="nt-trail"'));
assert.ok(shadow.includes('id="save-dialog"')&&shadow.includes('id="planner-sheet"'));
new Function(planner);
for(const match of host.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g))
 if(match[1].trim())new Function(match[1]);
const lifecycle=planner.slice(planner.indexOf('const plannerLayers=()=>'));
assert.ok(lifecycle.includes('plannerLayers().forEach(layer=>{if(map.hasLayer(layer))map.removeLayer(layer);})'));
assert.ok(lifecycle.includes('host.hidden=false;document.body.classList.add(\'nt-planner-on\')'));
assert.ok(lifecycle.includes('host.hidden=true;document.body.classList.remove(\'nt-planner-on\')'));
assert.ok(lifecycle.includes('map.invalidateSize({pan:false})'));
console.log('PASS: one Leaflet map, scoped planner UI, original map controls, routing CSP, local storage isolation and GPX safety');
