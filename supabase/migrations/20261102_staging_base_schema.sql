-- NORDIC TRAIL | STAGING ONLY | Base schema (no user data)
-- Run ONLY in Nordic-Trail-Staging after confirming project name.
-- Creates base tables and constraints. No policies, triggers or RPCs yet.
-- Until RLS policies are installed, tables are intentionally inaccessible via Data API.
BEGIN;
CREATE TABLE public.app_admins (
 user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.map_points (
 id bigint GENERATED BY DEFAULT AS IDENTITY,
 created_at timestamptz NOT NULL DEFAULT now(),
 kind text NOT NULL,
 status text NOT NULL,
 note text,
 lat double precision NOT NULL,
 lon double precision NOT NULL,
 user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE RESTRICT,
 visibility text NOT NULL DEFAULT 'private',
 review_status text NOT NULL DEFAULT 'pending',
 CONSTRAINT "Map_poits_pkey" PRIMARY KEY (id),
 CONSTRAINT map_points_kind_check CHECK (kind IN ('gate','closed','place')),
 CONSTRAINT map_points_status_check CHECK (
  (kind='gate' AND status IN ('Otwarty','Zamknięty','Nieznany')) OR
  (kind='closed' AND status IN ('Przejezdna','Nieprzejezdna','Do sprawdzenia')) OR
  (kind='place' AND status IN ('Dostępne','Niedostępne'))
 ),
 CONSTRAINT map_points_review_visibility_check CHECK (
  (review_status='pending' AND visibility='private') OR
  (review_status='approved' AND visibility='public') OR
  (review_status='rejected' AND visibility='private')
 )
);
CREATE TABLE public.point_reports (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 created_at timestamptz NOT NULL DEFAULT now(),
 point_id bigint NOT NULL REFERENCES public.map_points(id),
 user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE RESTRICT,
 report_type text NOT NULL,
 review_status text NOT NULL DEFAULT 'pending',
 note text,
 CONSTRAINT point_reports_status_check CHECK (review_status IN ('pending','approved','rejected')),
 CONSTRAINT point_reports_type_check CHECK (report_type IN
 ('gate_removed','gate_status','closure_risk','private_road','incorrect_info','other','road_unblocked'))
);
CREATE TABLE public.moderation_history (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 report_id bigint NOT NULL REFERENCES public.point_reports(id),
 admin_id uuid NOT NULL REFERENCES auth.users(id),
 old_status text NOT NULL,
 new_status text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT moderation_history_new_status_check CHECK (new_status IN ('approved','rejected'))
);
CREATE TABLE public.point_moderation_history (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 point_id bigint NOT NULL REFERENCES public.map_points(id),
 admin_id uuid NOT NULL REFERENCES auth.users(id),
 old_status text NOT NULL,
 new_status text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT point_moderation_history_old_status_check CHECK (old_status='pending'),
 CONSTRAINT point_moderation_history_new_status_check CHECK (new_status IN ('approved','rejected'))
);
ALTER TABLE public.app_admins ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.map_points ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.point_reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.moderation_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.point_moderation_history ENABLE ROW LEVEL SECURITY;
-- Explicitly remove API grants until reviewed policy/trigger/RPC installation.
REVOKE ALL ON public.app_admins,public.map_points,public.point_reports,
 public.moderation_history,public.point_moderation_history FROM anon,authenticated;
COMMIT;
